export const THEME_COLOR_KEYS = Object.keys(DARK_THEME_PRESETS.moss);
export const THEME_PRESETS = Object.fromEntries(Object.keys(DARK_THEME_PRESETS).flatMap(name => [
  [name, { palette: name, style: 'classic' }],
  [`${name}-blocks`, { palette: name, style: 'blocks' }]
]));

export function resolveThemeMode(preference, systemDark) {
  return preference === 'light' || preference === 'dark' ? preference : systemDark ? 'dark' : 'light';
}

export function themeColors(name, mode) {
  const presets = mode === 'light' ? LIGHT_THEME_PRESETS : DARK_THEME_PRESETS;
  return presets[THEME_PRESETS[name]?.palette] || presets.moss;
}

