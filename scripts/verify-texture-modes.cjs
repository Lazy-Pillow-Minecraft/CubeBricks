// Electron integration check using its own temporary profile, without desktop control.
const { app, BrowserWindow } = require('electron');
const fs = require('node:fs');
const path = require('node:path');
const os = require('node:os');
const profile = fs.mkdtempSync(path.join(os.tmpdir(), 'cubebricks-texture-modes-'));
app.setPath('userData', profile);
app.setPath('sessionData', profile);
const errors = [];
app.on('web-contents-created', (_event, contents) => contents.on('console-message', details => {
  if (details.level === 'error') errors.push(details.message);
}));
app.on('browser-window-created', (_event, win) => {
  win.hide();
  win.webContents.setBackgroundThrottling(false);
});
require('../electron/main.cjs');
app.whenReady().then(async () => {
  let report;
  try {
    const contents = BrowserWindow.getAllWindows()[0].webContents;
    if (contents.isLoading()) await new Promise(resolve => contents.once('did-finish-load', resolve));
    report = await contents.executeJavaScript(`(async()=>{
      const wait=ms=>new Promise(resolve=>setTimeout(resolve,ms));
      const check=(value,message)=>{if(!value) throw Error(message);};
      const same=(a,b)=>JSON.stringify(a)===JSON.stringify(b);
      for(let i=0;i<100&&document.querySelector('#startupCover');i++) await wait(50);
      document.querySelector('[data-home-format="bedrock_entity"]').click();
      document.querySelector('[data-action="addCube"]').click();
      document.querySelector('[data-action="createTexture"]').click();
      document.querySelector('#textureCreateType').value='solid';
      document.querySelector('#textureCreateWidth').value='8';document.querySelector('#textureCreateHeight').value='4';
      document.querySelector('#textureCreateForm').dispatchEvent(new Event('submit',{bubbles:true,cancelable:true}));
      const {state}=await import('./editor/state.js');
      const {Cube}=await import('./model.js');
      const asset=state.textureAssets[0], cube=state.project.getNode(state.selectedUid);
      check(asset&&cube,'Test texture and cube were created');
      const texture=asset.uuid||asset.id||asset._uid;
      cube.uvMode='face'; cube.autoUv=false;
      cube.faces={north:{texture,uv:[1,2,7,3],rotation:90}};
      const uv=JSON.stringify(cube.faces.north.uv);
      state.selectedUvFaces=new Set([cube.uid+'::north']);
      state.uvPreviewSelectedFace={uid:cube.uid,faceName:'north'};
      const mode=value=>{const select=document.querySelector('[data-texture-mode]');select.value=value;select.dispatchEvent(new Event('change',{bubbles:true}));};
      const fields=()=>[...document.querySelectorAll('[data-uv-coordinate]')];
      const edit=(index,value)=>{const input=fields()[index];input.value=String(value);input.dispatchEvent(new Event('change',{bubbles:true}));};
      mode('tiled');
      check(same(fields().map(input=>Number(input.value)),[0,0,16,16]),'Tiled fields show offset and size defaults');
      edit(0,-3);edit(1,2.5);edit(2,8);edit(3,4);
      check(JSON.stringify(cube.faces.north.uv)===uv,'Tiled edits preserve regular UVs');
      check(cube.faces.north.rotation===90,'Tiled edits preserve ordinary face rotation');
      mode('default');
      check(same(fields().map(input=>Number(input.value)),[1,2,6,1]),'Normal mode displays origin and dimensions');
      edit(0,0);edit(2,5);
      check(same(cube.faces.north.uv,[0,2,5,3]),'UV origin and width edits update both endpoints correctly');
      cube.faces.north.uv=JSON.parse(uv);
      mode('tiled');
      check(same(fields().map(input=>Number(input.value)),[-3,2.5,8,4]),'Tiled parameters survive round trips');
      const other=new Cube({faces:{north:{texture,uv:[4,1,6,3]}}});state.project.addElement(other);
      state.selectedUids.add(other.uid);state.selectedUvFaces.add(other.uid+'::north');
      mode('default');mode('tiled');
      check(fields()[0].value===''&&fields()[2].value==='','Mixed values are blank');
      edit(0,5);
      check(cube.faces.north.tiling.offsetX===5&&other.faces.north.tiling.offsetX===5,'Tiled edits apply to all selected faces');
      check(same(other.faces.north.uv,[4,1,6,3]),'Batch edits preserve every regular UV');
      state.selectedUvFaces.clear();
      document.querySelector('[data-texture-face="north"]').click();
      check(state.selectedUvFaces.size===2,'Direction buttons select tiled faces');
      cube.uvMode='box';mode('default');mode('tiled');
      check(fields().every(input=>!input.disabled),'Box UV restrictions do not disable independent tiled coordinates');
      const animation=document.querySelector('[data-texture-animation]');animation.checked=true;animation.dispatchEvent(new Event('change',{bubbles:true}));
      check(asset.mode==='tiled'&&asset.animation.enabled,'Flipbook is an additional attribute on tiled textures');
      mode('default');mode('tiled');
      await wait(1100);edit(0,6);await wait(1100);
      document.querySelector('[data-action="undo"]').click();
      for(let i=0;i<100&&state.project.getNode(cube.uid).faces.north.tiling.offsetX!==5;i++) await wait(50);
      check(state.project.getNode(cube.uid).faces.north.tiling.offsetX===5,'Undo restores tiled parameters');
      check(JSON.stringify(state.project.getNode(cube.uid).faces.north.uv)===uv,'Undo preserves ordinary UV data');
      document.querySelector('[data-action="redo"]').click();
      for(let i=0;i<100&&state.project.getNode(cube.uid).faces.north.tiling.offsetX!==6;i++) await wait(50);
      check(state.project.getNode(cube.uid).faces.north.tiling.offsetX===6,'Redo restores tiled parameters');
      for(let i=0;i<35;i++){const button=document.querySelector('[data-add-layer]');button.click();await wait(5);}
      await wait(300);
      document.querySelector('[data-open-layer-editor]').click();await wait(100);
      const scroller=document.querySelector('#layerEditorListHost .texture-layer-panel-scroll');
      scroller.scrollTop=0;await wait(30);
      const header=scroller.querySelector('.texture-layer-panel-header');
      const before=header.getBoundingClientRect().top;
      check(Math.abs(before-scroller.getBoundingClientRect().top)<=1,'Fixed header starts flush with the top of its content area');
      scroller.scrollTop=500;await wait(30);
      check(Math.abs(header.getBoundingClientRect().top-before)<=1,'Mode and layer creation controls remain fixed while scrolling');
      const {tiledFaceRaster,tiledFaceRegions}=await import('./common/core/texture-features.js');
      const source=document.createElement('canvas');source.width=source.height=2;
      const context=source.getContext('2d');const pixels=context.createImageData(2,2);
      pixels.data.set([255,0,0,255,0,255,0,255,0,0,255,255,255,255,0,255]);context.putImageData(pixels,0,0);
      const target={size:[80,40,2],faces:{north:{tiling:{width:8,height:4,offsetX:1,offsetY:0}}}};
      const raster=tiledFaceRaster(target,'north',source), data=raster.getContext('2d').getImageData(0,0,raster.width,raster.height).data;
      check(raster.width===8&&raster.height===4,'Tiled width and height define the entire face pixel extent');
      check(same([...data.slice(0,4)],[0,255,0,255])&&same([...data.slice(8,12)],[0,255,0,255]),'Offsets and repeated pixels render correctly');
      await wait(100);
      check(document.querySelector('#sceneCanvas').getContext('webgl').getError()===0,'Tiled scene has no WebGL errors');
      const {verifyTiledPaint}=await import('../scripts/verify-tiled-paint.mjs');
      const paint=await verifyTiledPaint();
      document.querySelector('#closeLayerEditor').click();
      const second={_uid:'focus_texture',uuid:'focus_texture',name:'focus.png',source:source.toDataURL(),uvWidth:2,uvHeight:2,kind:'IMAGE'};
      state.textureAssets.push(second);
      const current=state.project.getNode(cube.uid);
      current.uvMode='face';current.autoUv=false;
      current.faces=Object.fromEntries(['north','south','east','west','up','down'].map(faceName=>[faceName,{texture:second.uuid,uv:[0,0,2,2]}]));
      state.selectedUid=current.uid;state.selectedUids=new Set([current.uid]);
      mode('default');mode('tiled');
      const enabled=document.querySelector('#uvPreviewEnabled');enabled.checked=true;enabled.dispatchEvent(new Event('change',{bubbles:true}));
      const autoFocus=document.querySelector('#uvPreviewAutoFocusTexture');autoFocus.checked=true;autoFocus.dispatchEvent(new Event('change',{bubbles:true}));
      await wait(250);
      const preview=document.querySelector('#uvPreviewViewport'),rect=document.querySelector('#uvPreviewCanvas').getBoundingClientRect();
      const capture=preview.setPointerCapture,release=preview.releasePointerCapture;
      preview.setPointerCapture=preview.releasePointerCapture=()=>{};
      try {
        const options={bubbles:true,pointerId:42,button:0,clientX:rect.left+rect.width/2,clientY:rect.top+rect.height/2};
        preview.dispatchEvent(new PointerEvent('pointerdown',options));
        preview.dispatchEvent(new PointerEvent('pointerup',options));
      } finally {preview.setPointerCapture=capture;preview.releasePointerCapture=release;}
      await wait(350);
      check(state.activeTextureUid===second._uid,'UV Preview auto-focus switches to the selected face texture');
      check(state.selectedUvFaces.size===1,'Texture switching retains the clicked UV face');
      return {ok:true,checks:['mode round trip','independent parameters','origin and dimensions','batch edit','direction selection','box UV','undo and redo','flipbook placeholder','flush fixed header','whole face raster','WebGL','preview texture auto-switch'],paint};
    })()`);
    if (errors.length) throw Error(errors.join('\n'));
  } catch (error) { report = { ok: false, error: error.stack, errors }; }
  const output = path.resolve(process.argv.find(arg => arg.startsWith('--output='))?.slice(9) || 'build/performance/texture-modes.json');
  fs.mkdirSync(path.dirname(output), { recursive: true });
  fs.writeFileSync(output, JSON.stringify(report, null, 2));
  console.log(JSON.stringify(report));
  app.exit(report.ok ? 0 : 1);
});
