// Extract source-facing UI literals into one auditable translation inventory.
// Run after editing UI: node scripts/extract-ui-text.mjs
import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { translateUiText } from '../src/common/config/app-config.js';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const source = path.join(root, 'src');
const catalogPath = path.join(root, 'src', 'common', 'config', 'ui-text-catalog.json');
const previous = JSON.parse(await fs.readFile(catalogPath, 'utf8'));
const previousBySource = new Map(previous.entries.map(entry => [entry.zhHant, entry]));
const usedKeys = new Set(previous.entries.map(entry => entry.key).filter(Boolean));
const locations = new Map();
const han = /[\u3400-\u9fff]/;
const ignored = new Set();
async function visit(folder) {
  for (const entry of await fs.readdir(folder, { withFileTypes: true })) {
    const file = path.join(folder, entry.name);
    if (entry.isDirectory()) { if (entry.name !== 'assets') await visit(file); continue; }
    if (!/\.(?:js|html)$/.test(entry.name) || ignored.has(entry.name)) continue;
    const contents = await fs.readFile(file, 'utf8');
    const relative = path.relative(root, file).replaceAll('\\', '/');
    if (relative === 'src/common/i18n/simplified.js' || relative === 'src/common/i18n/messages.js') continue;
    const conversionTableStart = entry.name === 'app-config.js' ? contents.indexOf('const SIMPLIFIED_PHRASES') : -1;
    const conversionTableEnd = conversionTableStart < 0 ? -1 : contents.indexOf('function toSimplified', conversionTableStart);
    const translatorStart = entry.name === 'app-config.js' ? contents.indexOf('export function translateUiText')
      : entry.name === 'english.js' ? contents.indexOf('export function translateEnglishUiText') : -1;
    const translatorEnd = translatorStart < 0 ? -1 : entry.name === 'english.js'
      ? contents.length : contents.indexOf('let activeLanguage', translatorStart);
    const candidates = entry.name.endsWith('.html')
      ? [...contents.matchAll(/>\s*([^<>]*[\u3400-\u9fff][^<>]*?)\s*</g)].map(match => ({ text: match[1], index: match.index }))
        .concat([...contents.matchAll(/(?:title|aria-label|placeholder|alt)="([^"]*[\u3400-\u9fff][^"]*)"/g)]
          .map(match => ({ text: match[1], index: match.index })))
      : [...contents.matchAll(/'(?:\\.|[^'\\])*'|"(?:\\.|[^"\\])*"|`(?:\\.|[^`\\])*`/g)]
        .map(match => ({ text: match[0].slice(1, -1), index: match.index }));
    for (const candidate of candidates) {
      if (conversionTableStart >= 0 && candidate.index >= conversionTableStart && candidate.index < conversionTableEnd) continue;
      if (translatorStart >= 0 && candidate.index >= translatorStart && candidate.index < translatorEnd) continue;
      const text = candidate.text.trim().replace(/\s+/g, ' ');
      if (!han.test(text) || text.length < 2 || text.length > 240 || /^[,);}]/.test(text) || /<[^>]+>/.test(text)
        || /^disabled\b/.test(text) || /\.(?:png|jpg|jpeg|webp)$/i.test(text)) continue;
      const line = contents.slice(0, candidate.index).split('\n').length;
      const used = locations.get(text) || new Set();
      used.add(`${relative}:${line}`);
      locations.set(text, used);
    }
  }
}
await visit(source);
function assignKey(en) {
  const slug = String(en).toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '').slice(0, 100).replace(/-$/g, '') || 'message';
  let key = `ui.${slug}`;
  let suffix = 2;
  while (usedKeys.has(key)) key = `ui.${slug}-${suffix++}`;
  usedKeys.add(key);
  return key;
}
const entries = [...locations].sort(([a], [b]) => a.localeCompare(b, 'zh-Hant')).map(([zhHant, used]) => {
  const old = previousBySource.get(zhHant);
  const en = old?.en || translateUiText(zhHant, 'en');
  return {
    key: old?.key || assignKey(en), zhHant,
    zhHans: old?.zhHans === old?.zhHant ? translateUiText(zhHant, 'zh-Hans') : old?.zhHans || translateUiText(zhHant, 'zh-Hans'),
    en, dynamic: zhHant.includes('${'), englishMissing: en === zhHant,
    locations: [...used].sort()
  };
});
for (const old of previous.entries) {
  if (!old.locations?.length && !locations.has(old.zhHant)) entries.push({
    ...old,
    zhHans: old.zhHans === old.zhHant ? translateUiText(old.zhHant, 'zh-Hans') : old.zhHans
  });
}
entries.sort((a, b) => a.key.localeCompare(b.key));
await fs.writeFile(catalogPath,
  `${JSON.stringify({ generatedBy: 'node scripts/extract-ui-text.mjs', entries }, null, 2)}\n`);
const messages = Object.fromEntries(entries.map(({ key, zhHant, zhHans, en }) => [key, { zhHant, zhHans, en }]));
await fs.writeFile(path.join(root, 'src', 'common', 'i18n', 'messages.js'),
  `// Generated by node scripts/extract-ui-text.mjs. Translation IDs are stable.\nexport const UI_MESSAGES = Object.freeze(${JSON.stringify(messages, null, 2)});\n`);
const staticMissing = entries.filter(entry => entry.englishMissing && !entry.dynamic).length;
const dynamicReview = entries.filter(entry => entry.dynamic && entry.englishMissing).length;
process.stdout.write(`Extracted ${entries.length} UI literals; ${staticMissing} static strings missing English, ${dynamicReview} dynamic templates queued for review.\n`);
