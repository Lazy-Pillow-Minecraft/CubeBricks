import assert from 'node:assert/strict';
import {createTextureFrameElement,insertTextureFrameElement,moveTextureFrameElement,textureFrameElements,migrateTextureAnimationMode} from '../src/texture/frame-elements.js';
import {activeTextureFrame,selectTextureFrame,frameLayerUids,setFrameLayerLink,FRAME_ROOT_UID,setFrameLayerVisibility,frameVisibilityControls,framePaintLayer,rememberFramePaintLayer,setTextureFramePosition,textureFramePosition,textureFrameSample} from '../src/common/core/frame-links.js';

const asset={mode:'tiled',source:'unchanged pixels',uvWidth:8,uvHeight:4,animation:{enabled:true,frames:[]}};
const first=createTextureFrameElement(),second=createTextureFrameElement([first]);
assert.equal(first.type,'frame');assert.notEqual(first.uid,second.uid);
assert.deepEqual(Object.keys(first).sort(),['name','type','uid']);
assert.deepEqual(textureFrameElements({}),[]);
asset.animation.frames=insertTextureFrameElement([],first);
asset.animation.frames=insertTextureFrameElement(textureFrameElements(asset),second,first.uid);
const duplicate=createTextureFrameElement([],first);
assert.equal(duplicate.name,first.name);assert.notEqual(duplicate.uid,first.uid);
const ordered=insertTextureFrameElement(textureFrameElements(asset),duplicate,first.uid);
assert.deepEqual(ordered.map(frame=>frame.uid),[first.uid,duplicate.uid,second.uid]);
assert.deepEqual(moveTextureFrameElement(ordered,first.uid,999).map(frame=>frame.uid),[duplicate.uid,second.uid,first.uid]);
assert.deepEqual(moveTextureFrameElement(ordered,second.uid,-999).map(frame=>frame.uid),[second.uid,first.uid,duplicate.uid]);
assert.equal(moveTextureFrameElement(ordered,first.uid,0),ordered);
assert.equal(asset.mode,'tiled');assert.equal(asset.source,'unchanged pixels');assert.deepEqual([asset.uvWidth,asset.uvHeight],[8,4]);
const legacy={mode:'animation',source:'unchanged pixels',animation:{frames:[first]}};migrateTextureAnimationMode(legacy);
assert.equal(legacy.mode,'default');assert.equal(legacy.animation.enabled,true);assert.equal(legacy.source,'unchanged pixels');
assert.equal(legacy.animation.frames[0],first);
asset.layers=[{uid:'bottom'},{uid:'group',type:'group'},{uid:'nested',type:'group',parentUid:'group'},
  {uid:'child',parentUid:'nested'},{uid:'sibling',parentUid:'group'},{uid:'unrelated'}];
assert.equal(activeTextureFrame(asset).uid,first.uid);
assert.equal(setFrameLayerLink(asset,first.uid,'child',true),true);
assert.equal(setFrameLayerLink(asset,first.uid,'child',true),false);
assert.deepEqual([...frameLayerUids(asset)].sort(),['child','group','nested']);
assert.equal(setFrameLayerLink(asset,second.uid,'group',true),true);
assert.equal(setFrameLayerLink(asset,second.uid,'child',true),true);
selectTextureFrame(asset,second.uid);
assert.deepEqual([...frameLayerUids(asset)].sort(),['child','group','nested','sibling']);
assert.equal(setFrameLayerLink(asset,first.uid,'missing',true),false);
assert.equal(setFrameLayerLink(asset,first.uid,'child',false),true);
assert.deepEqual(frameLayerUids(asset,asset.animation.frames[0]),new Set());
selectTextureFrame(asset,'deleted-frame');assert.equal(activeTextureFrame(asset).uid,first.uid);
assert.equal(setFrameLayerLink(asset,first.uid,FRAME_ROOT_UID,true),true);
assert.equal(frameLayerUids(asset).size,asset.layers.length);
assert.equal(frameVisibilityControls(asset).size,asset.layers.length);
assert.equal(setFrameLayerVisibility(asset,'group',false),true);
assert.deepEqual([...frameLayerUids(asset)].sort(),['bottom','unrelated']);
selectTextureFrame(asset,second.uid);assert.ok(frameLayerUids(asset).has('child'),'frame visibility is independent');
assert.equal(rememberFramePaintLayer(asset,'sibling'),true);assert.equal(framePaintLayer(asset).uid,'sibling');
assert.equal(rememberFramePaintLayer(asset,'bottom'),false);assert.equal(rememberFramePaintLayer(asset,'group'),false);
selectTextureFrame(asset,first.uid);assert.equal(framePaintLayer(asset).uid,'unrelated');
selectTextureFrame(asset,second.uid);assert.equal(framePaintLayer(asset).uid,'sibling');
const cloned=createTextureFrameElement([],activeTextureFrame(asset));cloned.visibility={child:false};cloned.layerUids.push('bottom');
assert.equal(activeTextureFrame(asset).layerUids.includes('bottom'),false);
setTextureFramePosition(asset,.5);asset.animation.interpolate=true;
assert.equal(textureFramePosition(asset),.5);assert.equal(textureFrameSample(asset).mix,.5);assert.equal(textureFrameSample(asset).next.uid,second.uid);
console.log('Frame metadata: identity, copy, insertion, ordering, mode migration and unchanged pixels passed.');
