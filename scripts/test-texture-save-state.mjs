import assert from 'node:assert/strict';
import { createTextureSaveIndicators, textureSaveFingerprint } from '../src/texture/save-state.js';
const wait = () => new Promise(resolve => setTimeout(resolve, 5));
async function until(test) {
  for (let n = 0; n < 100; n++) {
    if (test()) return;
    await wait();
  }
  throw Error('Texture indicator did not settle');
}
const source = 'data:image/png;base64,AQ==', edited = 'data:image/png;base64,Ag==';
const asset = { _uid: 'texture', source, externalFile: { imported: true } }, state = { textureAssets: [asset] };
const controls = createTextureSaveIndicators({ state, root: () => null });
controls.refresh();
await until(() => asset.externalFile.fingerprint);
assert.equal(controls.isDirty(asset), false, 'imported, untouched pixels begin clean');
const baseline = asset.externalFile.fingerprint;
asset.source = edited;
controls.refresh();
await until(() => controls.isDirty(asset));
assert.equal(asset.externalFile.fingerprint, baseline);
asset.source = source;
controls.refresh();
await until(() => !controls.isDirty(asset));
const created = { _uid: 'new', source };
state.textureAssets.push(created);
controls.refresh();
await wait();
assert.equal(controls.isDirty(created), true, 'new textures remain unsaved even if pixels match an imported image');
await controls.markSaved(created, await textureSaveFingerprint(created), { filePath: 'new.png', resource: 'demo:new' });
assert.equal(controls.isDirty(created), false);
created.layers = [{ uid: 'layer', source, visible: true, opacity: 100 }];
await controls.markSaved(created, await textureSaveFingerprint(created));
created.activeLayerUid = 'layer';
created.layers[0].collapsed = true;
created.layers[0].name = 'renamed';
controls.refresh();
await wait();
assert.equal(controls.isDirty(created), false, 'selection and list presentation do not dirty exported pixels');
created.layers[0].opacity = 50;
controls.refresh();
await until(() => controls.isDirty(created));
const copied = structuredClone(asset);
copied._uid = 'copy';
delete copied.externalFile;
state.textureAssets.push(copied);
controls.refresh();
await wait();
assert.equal(controls.isDirty(copied), true);
const latest = { _uid: 'disk-state', source }, previous = { imported: true, fingerprint: await textureSaveFingerprint({ source }) };
state.textureAssets.push(latest);
latest.source = edited;
await controls.markSaved(latest, await textureSaveFingerprint(latest), { filePath: 'disk.png' });
const undone = { _uid: latest._uid, source, externalFile: previous };
state.textureAssets[state.textureAssets.indexOf(latest)] = undone;
controls.refresh();
await until(() => controls.isDirty(undone));
assert.notEqual(undone.externalFile.fingerprint, previous.fingerprint, 'undo cannot roll back the actual file save baseline');
console.log('Texture save state: imports, edits, undo, independent copies, metadata and saved baselines passed.');
