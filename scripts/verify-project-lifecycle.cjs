const { app, BrowserWindow } = require('electron');
const fs = require('node:fs');
const path = require('node:path');
const os = require('node:os');
const profile = fs.mkdtempSync(path.join(os.tmpdir(), 'cubebricks-lifecycle-'));
app.setPath('userData', profile);
app.setPath('sessionData', profile);
const errors = [];
app.on('web-contents-created', (_event, contents) => contents.on('console-message', details => {
  if (details.level === 'error') errors.push(details.message);
}));
app.on('browser-window-created', (_event, win) => {
  win.hide();
  win.webContents.setBackgroundThrottling(false);
});
require('../electron/main.cjs');
app.whenReady().then(async () => {
  let report;
  try {
    const contents = BrowserWindow.getAllWindows()[0].webContents;
    if (contents.isLoading()) await new Promise(resolve => contents.once('did-finish-load', resolve));
    report = await contents.executeJavaScript(`(async()=>{
      const wait=ms=>new Promise(resolve=>setTimeout(resolve,ms));
      const check=(value,message)=>{if(!value)throw Error(message);};
      const until=async(test,message)=>{for(let i=0;i<100;i++){if(await test())return;await wait(40);}throw Error(message);};
      const tabs=()=>[...document.querySelectorAll('[data-project-tab]')];
      const desktop=window.cubeBricksDesktop;
      await until(()=>!document.querySelector('#startupCover'),'startup completes');
      check(tabs().length===1&&document.body.classList.contains('project-home-active'),'startup has a home tab');
      document.querySelector('[data-home-format="bedrock_entity"]').click();
      check(tabs().length===1&&!document.body.classList.contains('project-home-active'),'new project replaces its home tab');
      document.querySelector('[data-action="addCube"]').click();
      document.querySelector('[data-action="save"]').click();
      await until(async()=>(await desktop.listWorkspaceProjects()).some(project=>project.persistent&&project.elementCount===1),'save writes persistent retention metadata');
      const first=(await desktop.listWorkspaceProjects())[0],firstTab=tabs()[0].dataset.projectTab;
      document.querySelector('[data-action="addCube"]').click();
      document.querySelector('#newProjectTab').click();
      await until(()=>document.querySelector('[data-home-project]'),'home project listing loads');
      check(tabs().length===2&&document.body.classList.contains('project-home-active'),'plus preserves the model and adds an active home tab');
      const plus=document.querySelector('#newProjectTab').getBoundingClientRect(),last=tabs().at(-1).getBoundingClientRect();
      check(plus.left-last.right<10,'plus follows the last tab instead of aligning to the right');
      document.querySelector('[data-home-project="'+first.journalId+'"]').click();
      await until(()=>tabs().length===1&&!document.body.classList.contains('project-home-active'),'opening an already open project consumes only its home tab');
      check(tabs()[0].dataset.projectTab===firstTab,'opening an existing tab retains its identity');
      document.querySelector('#newProjectTab').click();
      document.querySelector('[data-home-format="bedrock_entity"]').click();
      check(tabs().length===2,'new creation replaces the second home without disturbing the first project');
      const secondTab=tabs().at(-1).dataset.projectTab;
      const closeSecond=()=>document.querySelector('[data-close-project-tab="'+secondTab+'"]').click();
      closeSecond();await until(()=>document.querySelector('.app-prompt-dialog[open]'),'never saved project prompts on close');
      document.querySelectorAll('.app-prompt-dialog .dialog-actions button')[2].click();await wait(50);
      check(tabs().length===2,'cancel preserves the unsaved project');
      closeSecond();await until(()=>document.querySelector('.app-prompt-dialog[open]'),'close prompt appears again');
      document.querySelector('.app-prompt-dialog .dialog-actions button').click();
      await until(()=>tabs().length===1,'save and close finishes its durable write');
      const second=(await desktop.listWorkspaceProjects()).find(project=>project.journalId!==first.journalId);
      check(second?.persistent,'retaining an unsaved project marks it permanently saved');
      document.querySelector('[data-close-project-tab="'+firstTab+'"]').click();
      await until(()=>document.body.classList.contains('project-home-active'),'saved project closes directly to home');
      check(!document.querySelector('.app-prompt-dialog[open]'),'saved dirty project does not prompt');
      const saved=(await desktop.listWorkspaceProjects()).find(project=>project.journalId===first.journalId);
      check(saved?.persistent&&saved.elementCount===2,'saved project auto-saves later edits without deleting its folder');
      document.querySelector('#homeRefreshProjects').click();
      await until(()=>document.querySelector('[data-home-project="'+first.journalId+'"]'),'home lists the closed saved project');
      const deleteFirst=async()=>{
        const card=document.querySelector('[data-home-project="'+first.journalId+'"]');
        card.dispatchEvent(new MouseEvent('contextmenu',{bubbles:true,cancelable:true,clientX:400,clientY:300}));
        document.querySelector('#contextMenu button').click();
        await until(()=>document.querySelector('.app-prompt-dialog[open]'),'delete requires confirmation');
      };
      await deleteFirst();document.querySelectorAll('.app-prompt-dialog .dialog-actions button')[1].click();await wait(80);
      check((await desktop.listWorkspaceProjects()).some(project=>project.journalId===first.journalId),'canceling deletion preserves the folder');
      await deleteFirst();document.querySelector('.app-prompt-dialog .dialog-actions button').click();
      await until(async()=>!(await desktop.listWorkspaceProjects()).some(project=>project.journalId===first.journalId),'confirmed deletion removes only its target');
      check((await desktop.listWorkspaceProjects()).some(project=>project.journalId===second.journalId),'another project survives deletion');
      document.querySelector('[data-home-project="'+second.journalId+'"]').click();
      await until(()=>!document.body.classList.contains('project-home-active'),'saved folder reopens into its home tab');
      document.querySelector('#newProjectTab').click();
      await until(()=>document.querySelector('[data-home-project="'+second.journalId+'"]'),'home reloads beside the open project');
      const card=document.querySelector('[data-home-project="'+second.journalId+'"]');
      card.dispatchEvent(new MouseEvent('contextmenu',{bubbles:true,cancelable:true,clientX:400,clientY:300}));
      document.querySelector('#contextMenu button').click();await until(()=>document.querySelector('.app-prompt-dialog[open]'),'open project deletion prompts');
      document.querySelector('.app-prompt-dialog .dialog-actions button').click();
      await until(()=>tabs().length===1,'deleting an open project removes its project tab and preserves home');
      const {beginProjectOpenProgress}=await import('./project/open-progress.js');
      const fast=beginProjectOpenProgress();fast.finish();await wait(520);
      check(!document.querySelector('#projectOpenProgressDialog').open,'fast open never flashes a progress dialog');
      const slow=beginProjectOpenProgress();await wait(540);
      check(document.querySelector('#projectOpenProgressDialog').open,'slow open displays progress after half a second');slow.finish();
      return {ok:true,checks:['home tab','replace home on creation/open','left aligned plus','save retention','saved dirty close','unsaved close choices','confirmed delete','open project delete','500ms progress']};
    })()`);
    if (errors.length) throw Error(errors.join('\n'));
  } catch (error) { report = { ok: false, error: error.stack, errors }; }
  const output = path.resolve('build/performance/project-lifecycle.json');
  fs.mkdirSync(path.dirname(output), { recursive: true });
  fs.writeFileSync(output, JSON.stringify(report, null, 2));
  console.log(JSON.stringify(report));
  app.exit(report.ok ? 0 : 1);
});
